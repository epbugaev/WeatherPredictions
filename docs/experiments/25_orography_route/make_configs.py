"""Генератор 4 конфигов exp25 из родителя abl16_r3_a2_exp13_t12 (USA).

exp25 изолирует маршрут орографии: 2×2 (орография в диабатическом Q_theta: вкл/выкл)
× (орография входным каналом бэкбона: вкл/выкл). Все армы — PI-IAM4VP, USA, seed 0,
физика A2 включена везде (влажностная диабатика — константный фон, варьируем ТОЛЬКО
орографию). Родитель задаёт весь харнесс (500 эпох, батч, lr, окна данных).

| арм | оро в Q_theta | оро каналом | что это |
| --- | --- | --- | --- |
| d0 | ✗ | ✗ | baseline (орографии нет нигде) |
| d1 | ✓ | ✗ | оро только в диабатике (= abl16-r3, уже обучен 500) |
| d2 | ✗ | ✓ | оро только каналом |
| d3 | ✓ | ✓ | оро в обоих (= exp24-iam4vp-a2-orog) |

Маршрут «диабатика» = ключ ``diabatic_geo_fields`` (новый, см.
utils/physics_residual.py): полный ``[orography, lat, lsm]`` или урезанный
``[lat, lsm]``. Маршрут «канал» = механизм static-input exp24
(``static_input_fields=['orography']``). Спек: docs/experiments/25_orography_route/README.md.

Запуск (локально):
    python docs/experiments/25_orography_route/make_configs.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = REPO_ROOT / "configs" / "exp25"
PARENT = "configs/abl16_long/abl16_r3_a2_exp13_t12.yaml"

USA_CUT = [[75, 107], [164, 228]]
USA_CUT_FLAT = [75, 107, 164, 228]
CONSTANTS_PATH = "/home/fratnikov/weather_bench/1.40625deg/constants/constants_1.40625deg.nc"

GEO_FULL = ["orography", "lat", "lsm"]
GEO_NO_OROG = ["lat", "lsm"]

# арм -> (orog в диабатике?, orog каналом?)
ARMS: dict[str, tuple[bool, bool]] = {
    "d0": (False, False),
    "d1": (True, False),
    "d2": (False, True),
    "d3": (True, True),
}


def build_arm(config: dict, arm: str, orog_diabatic: bool, orog_channel: bool) -> dict:
    """Настроить загруженный родительский конфиг под арм exp25 (мутирует и возвращает).

    Args:
        config: разобранный YAML родителя (abl16_r3_a2_exp13_t12, USA).
        arm: короткий тег арма (``d0``..``d3``) для ``experiment.name``.
        orog_diabatic: подавать ли орографию в geo-вход Q_theta.
        orog_channel: подавать ли орографию входным каналом бэкбона.

    Returns:
        Тот же ``config`` с настроенным маршрутом орографии и именем.

    Raises:
        ValueError: родитель не USA (гард от неверной базы).
    """
    if config["data"]["cut"] != USA_CUT:
        raise ValueError(f"Родитель не USA: data.cut={config['data']['cut']}, ожидался {USA_CUT}")
    config["experiment"]["name"] = f"exp25-iam4vp-{arm}-usa-s0"
    config["training"]["seed"] = 0
    params = config["model"]["params"]
    # Маршрут «диабатика»: явно фиксируем geo-поля (в т.ч. полный набор — для записи).
    params["diabatic_geo_fields"] = list(GEO_FULL if orog_diabatic else GEO_NO_OROG)
    # Маршрут «канал»: static-input с одной орографией либо его отсутствие.
    if orog_channel:
        params["static_input_fields"] = ["orography"]
        params["static_constants_path"] = CONSTANTS_PATH
        params["static_cut"] = list(USA_CUT_FLAT)
    else:
        for key in ("static_input_fields", "static_constants_path", "static_cut"):
            params.pop(key, None)
    return config


def main() -> None:
    """Сгенерировать 4 конфига exp25 в ``configs/exp25/``. Side effect: пишет YAML."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    parent_text = (REPO_ROOT / PARENT).read_text()
    written = 0
    for arm, (orog_diabatic, orog_channel) in ARMS.items():
        config = build_arm(yaml.safe_load(parent_text), arm, orog_diabatic, orog_channel)
        header = (
            f"# GENERATED by docs/experiments/25_orography_route/make_configs.py from {PARENT}.\n"
            f"# Do not edit by hand — regenerate. Arm={arm}: "
            f"orog_in_diabatic={orog_diabatic}, orog_as_channel={orog_channel}, "
            "region=usa, seed=0.\n"
        )
        body = yaml.safe_dump(config, sort_keys=False, allow_unicode=True, default_flow_style=False)
        (OUT_DIR / f"exp25_iam4vp_{arm}_usa.yaml").write_text(header + body)
        written += 1
    print(f"[make_configs] {written} конфигов -> {OUT_DIR}")  # noqa: T201


if __name__ == "__main__":
    main()
