"""Генератор конфигов exp26 — статические входы exp24 на France и North Pacific.

exp26 переносит матрицу exp24 (статические входы: орография / орография+lsm,
армы no_physics и A2-exp13) на два новых региона, чтобы проверить, держатся ли
выводы exp24 (орография — достаточный статический сигнал; физика A2 даёт ~−2.7 %
поверх статики) вне USA. Регион меняет РОВНО геометрию, всё остальное (бюджет
эпох, батч, lr, набор статических полей, физрежим) наследуется от USA-конфига
exp24 бит-в-бит — DRY, как в exp22.

Меняются поля:
  * ``data.cut`` — окно кропа региона (оба 32×64);
  * ``model.params.static_cut`` — тот же cut плоским списком (кроп чтения констант
    орографии/lsm для входных каналов; есть во ВСЕХ armах exp24);
  * ``model.params.diabatic_cut`` — тот же cut плоским списком (только A2-арм с
    диабатикой; глобальные константы режутся этим окном);
  * ``model.params.physics_lat_start_deg`` — широта первого латентного ряда;
  * ``experiment.name`` → ``exp26-<fam>-<arm>-<tag>-<region>-s0``.

``physics_dlat_deg/dlon`` (5.625) регион-независимы и не трогаются. Мемап региона
подаётся через ``ORIG_MEMMAP`` при запуске, поэтому ``memmap_path`` остаётся null.

Запуск (локально):
    python docs/experiments/26_cross_region_static/make_configs.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = REPO_ROOT / "configs" / "exp26"

# Регион: cut (для data.cut), тот же плоским (static_cut/diabatic_cut) и широта
# первого латентного ряда physics_lat_start_deg = -90 + (lat0+2)*1.40625.
REGIONS: dict[str, dict] = {
    "france": {
        "cut": [[81, 113], [0, 64]],
        "cut_flat": [81, 113, 0, 64],
        "physics_lat_start_deg": 26.71875,
    },
    "npac": {
        "cut": [[74, 106], [96, 160]],
        "cut_flat": [74, 106, 96, 160],
        "physics_lat_start_deg": 16.875,
    },
}

# Базовые USA-конфиги exp24 (seed 0) — та же матрица, что дала результат exp24.
# Все 3 семейства несут полный A/B (orog / static) — orog-only для PredRNNv2/
# SimVPv2 добавлен расширением (закрывает пробел матрицы, см. артефакт аудита).
# Порядок стемов — как в configs/exp24/.
BASE_CONFIGS: list[str] = [
    "configs/exp24/exp24_iam4vp_nophys_orog_usa.yaml",
    "configs/exp24/exp24_iam4vp_a2_orog_usa.yaml",
    "configs/exp24/exp24_iam4vp_nophys_static_usa.yaml",
    "configs/exp24/exp24_iam4vp_a2_static_usa.yaml",
    "configs/exp24/exp24_predrnnv2_nophys_orog_usa.yaml",
    "configs/exp24/exp24_predrnnv2_a2_orog_usa.yaml",
    "configs/exp24/exp24_predrnnv2_nophys_static_usa.yaml",
    "configs/exp24/exp24_predrnnv2_a2_static_usa.yaml",
    "configs/exp24/exp24_simvpv2_nophys_orog_usa.yaml",
    "configs/exp24/exp24_simvpv2_a2_orog_usa.yaml",
    "configs/exp24/exp24_simvpv2_nophys_static_usa.yaml",
    "configs/exp24/exp24_simvpv2_a2_static_usa.yaml",
]


def regionalize(config: dict, stem: str, region_key: str, region: dict) -> dict:
    """Подставить региональные значения в exp24-USA-конфиг (мутирует и возвращает).

    Args:
        config: разобранный YAML базового USA-конфига exp24.
        stem: основа имени базового конфига (``exp24_<fam>_<arm>_<tag>_usa``).
        region_key: ``france`` / ``npac``.
        region: запись :data:`REGIONS` (cut, cut_flat, physics_lat_start_deg).

    Returns:
        Тот же ``config`` с региональной геометрией и новым ``experiment.name``.
    """
    tail = stem.removeprefix("exp24_").removesuffix("_usa")  # <fam>_<arm>_<tag>
    config["experiment"]["name"] = f"exp26-{tail.replace('_', '-')}-{region_key}-s0"
    config["data"]["cut"] = [list(pair) for pair in region["cut"]]

    params = config["model"]["params"]
    if "static_cut" in params:
        params["static_cut"] = list(region["cut_flat"])
    if "diabatic_cut" in params:
        params["diabatic_cut"] = list(region["cut_flat"])
    if "physics_lat_start_deg" in params:
        params["physics_lat_start_deg"] = region["physics_lat_start_deg"]
    return config


def out_stem(base_stem: str, region_key: str) -> str:
    """Имя выходного конфига: ``exp26_<fam>_<arm>_<tag>_<region>``."""
    tail = base_stem.removeprefix("exp24_").removesuffix("_usa")
    return f"exp26_{tail}_{region_key}"


def main() -> None:
    """Сгенерировать конфиги exp26 в ``configs/exp26/``. Side effect: пишет YAML."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    for base_rel in BASE_CONFIGS:
        base_path = REPO_ROOT / base_rel
        assert base_path.exists(), f"нет базового конфига {base_path}"
        base_stem = base_path.stem
        for region_key, region in REGIONS.items():
            config = regionalize(
                yaml.safe_load(base_path.read_text()), base_stem, region_key, region
            )
            out_path = OUT_DIR / f"{out_stem(base_stem, region_key)}.yaml"
            header = (
                f"# GENERATED by docs/experiments/26_cross_region_static/make_configs.py "
                f"from {base_rel}.\n# Do not edit by hand — regenerate. "
                f"Region={region_key} (cross-region replica of exp24 static inputs).\n"
            )
            body = yaml.safe_dump(
                config, sort_keys=False, allow_unicode=True, default_flow_style=False
            )
            out_path.write_text(header + body)
            written += 1
    print(f"[make_configs] {written} конфигов -> {OUT_DIR}")  # noqa: T201


if __name__ == "__main__":
    main()
