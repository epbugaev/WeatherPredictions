"""Генератор 6 конфигов exp24 из USA-конфигов баз exp16-long/exp20/exp21-long.

exp24 = 3 семейства × 2 арма (no_physics / A2 exp13), USA, seed 0, + статические
входные каналы (орография, lsm). Родительский конфиг определяет ВСЁ (бюджет
эпох, батч, lr, окна данных): пары «static vs база» сравниваются в одинаковом
харнессе. Скрипт добавляет РОВНО три ключа в ``model.params`` и меняет
``experiment.name`` (spec: docs/superpowers/specs/2026-07-16-exp24-static-inputs-design.md).

Запуск (локально):
    python docs/experiments/24_static_inputs/make_configs.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = REPO_ROOT / "configs" / "exp24"

USA_CUT = [[75, 107], [164, 228]]
USA_CUT_FLAT = [75, 107, 164, 228]
STATIC_FIELDS = ["orography", "lsm"]
CONSTANTS_PATH = "/home/fratnikov/weather_bench/1.40625deg/constants/constants_1.40625deg.nc"

# Наборы статических полей -> тег в имени конфига/эксперимента.
#   ``static`` = орография + маска суша/море (полный набор, все 3 семейства).
#   ``orog``   = ТОЛЬКО орография (S=1) — чистый A/B «без/с орографией», IAM4VP.
STATIC_SETS: dict[str, list[str]] = {
    "static": ["orography", "lsm"],
    "orog": ["orography"],
}

# (семейство, арм) -> базовый USA-конфиг (он же — бюджет эпох и весь харнесс).
BASE_CONFIGS: dict[tuple[str, str], str] = {
    ("iam4vp", "nophys"): "configs/abl16_long/abl16_r0_no_physics_t12.yaml",
    ("iam4vp", "a2"): "configs/abl16_long/abl16_r3_a2_exp13_t12.yaml",
    ("predrnnv2", "nophys"): "configs/exp20/exp20_p0_no_physics_s0.yaml",
    ("predrnnv2", "a2"): "configs/exp20/exp20_p3_a2_exp13_s0.yaml",
    ("simvpv2", "nophys"): "configs/exp21_long/exp21_s0_no_physics_t12_s0.yaml",
    ("simvpv2", "a2"): "configs/exp21_long/exp21_s3_a2_exp13_t12_s0.yaml",
}

# Какие (семейство, арм, тег-набора, сид) генерировать.
#   Полный static (orog+lsm) — для всех 3 семейств × 2 арма (исходная матрица 6, seed 0).
#   orography-only — только IAM4VP × 2 арма (чистый A/B «без/с орографией», seed 0).
#   Второй сид (s1) — IAM4VP, все 4 варианта (волна proj_1717).
JOBS: list[tuple[str, str, str, int]] = [
    *[(fam, arm, "static", 0) for (fam, arm) in BASE_CONFIGS],
    ("iam4vp", "nophys", "orog", 0),
    ("iam4vp", "a2", "orog", 0),
    ("iam4vp", "nophys", "static", 1),
    ("iam4vp", "a2", "static", 1),
    ("iam4vp", "nophys", "orog", 1),
    ("iam4vp", "a2", "orog", 1),
    # orog-only для PredRNNv2/SimVPv2 — закрывает пробел матрицы (см. exp26 README):
    # раньше orography-only арм был только у IAM4VP.
    ("predrnnv2", "nophys", "orog", 0),
    ("predrnnv2", "a2", "orog", 0),
    ("simvpv2", "nophys", "orog", 0),
    ("simvpv2", "a2", "orog", 0),
]


def config_stem(family: str, arm: str, tag: str, seed: int) -> str:
    """Имя конфига без расширения; seed 0 — без суффикса (истор. имена волны s0)."""
    suffix = "" if seed == 0 else f"_s{seed}"
    return f"exp24_{family}_{arm}_{tag}_usa{suffix}"


def staticize(config: dict, family: str, arm: str, fields: list[str], tag: str, seed: int) -> dict:
    """Добавить static-блок в загруженный USA-конфиг (мутирует и возвращает).

    Args:
        config: разобранный YAML родительского USA-конфига.
        family: ``iam4vp`` / ``predrnnv2`` / ``simvpv2``.
        arm: ``nophys`` / ``a2``.
        fields: подмножество ``["orography", "lsm"]`` — статические входные каналы.
        tag: короткий тег набора (``static`` / ``orog``) для имени эксперимента.
        seed: ``training.seed`` рана; входит в ``experiment.name`` (``-s<seed>``).

    Returns:
        Тот же ``config`` со static-ключами, сидом и новым ``experiment.name``.

    Raises:
        ValueError: родительский конфиг не USA (гард от неверной базы).
    """
    if config["data"]["cut"] != USA_CUT:
        raise ValueError(f"Родитель не USA: data.cut={config['data']['cut']}, ожидался {USA_CUT}")
    config["experiment"]["name"] = f"exp24-{family}-{arm}-{tag}-usa-s{seed}"
    config["training"]["seed"] = seed
    params = config["model"]["params"]
    params["static_input_fields"] = list(fields)
    params["static_constants_path"] = CONSTANTS_PATH
    params["static_cut"] = list(USA_CUT_FLAT)
    return config


def main() -> None:
    """Сгенерировать конфиги exp24 в ``configs/exp24/``. Side effect: пишет YAML."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    for family, arm, tag, seed in JOBS:
        base_rel = BASE_CONFIGS[(family, arm)]
        base_path = REPO_ROOT / base_rel
        assert base_path.exists(), f"нет базового конфига {base_path}"
        fields = STATIC_SETS[tag]
        config = staticize(yaml.safe_load(base_path.read_text()), family, arm, fields, tag, seed)
        out_path = OUT_DIR / f"{config_stem(family, arm, tag, seed)}.yaml"
        header = (
            f"# GENERATED by docs/experiments/24_static_inputs/make_configs.py "
            f"from {base_rel}.\n# Do not edit by hand — regenerate. "
            f"Arm={arm}, family={family}, static={'+'.join(fields)}, region=usa, seed={seed}.\n"
        )
        body = yaml.safe_dump(config, sort_keys=False, allow_unicode=True, default_flow_style=False)
        out_path.write_text(header + body)
        written += 1
    print(f"[make_configs] {written} конфигов -> {OUT_DIR}")  # noqa: T201


if __name__ == "__main__":
    main()
